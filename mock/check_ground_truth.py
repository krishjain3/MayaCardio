"""
check_ground_truth test tool conforming to Section 4 and Section 6 of the MayaCardio assessment.
Compares pipeline export files against expected ground truth generated by biosignal-mock.
Checks:
- Criterion 1: Every received sample is on disk, exactly once, unchanged.
- Criterion 2: Every missing sample is listed as lost, with a reason (no silent loss allowed).
"""

import argparse
import json
import sys
from typing import Dict, List, Optional, Set, Tuple
from mock.biosignal_mock import BiosignalGenerator


def check_export(
    export_file_path: str,
    mode: str = "signal",
    seed: int = 7,
    expected_samples: Optional[int] = None
) -> Tuple[bool, Dict[str, any]]:
    generator = BiosignalGenerator(mode=mode, seed=seed)

    samples: Dict[Tuple[int, int], List[int]] = {}
    losses: List[Dict[str, any]] = []
    duplicates: List[Tuple[int, int]] = []
    value_mismatches: List[Dict[str, any]] = []

    with open(export_file_path, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except Exception as e:
                return False, {"error": f"Invalid JSON on line {line_num}: {e}"}

            if "values" in rec:
                sensor = rec["sensor"]
                idx = rec["index"]
                vals = rec["values"]
                key = (sensor, idx)

                if key in samples:
                    duplicates.append(key)
                else:
                    samples[key] = vals

                # Verify values match ground truth
                expected_vals = generator.get_sample(sensor, idx)
                if vals != expected_vals:
                    value_mismatches.append({
                        "sensor": sensor,
                        "index": idx,
                        "got": vals,
                        "expected": expected_vals
                    })

            elif "from_index" in rec:
                losses.append(rec)
            else:
                return False, {"error": f"Unrecognized record on line {line_num}: {rec}"}

    # Analyze coverage and silent losses
    silent_losses: List[Dict[str, any]] = []
    sensor_counts = {1: 0, 2: 0}
    max_indices = {1: -1, 2: -1}

    for (sensor, idx) in samples.keys():
        sensor_counts[sensor] += 1
        if idx > max_indices[sensor]:
            max_indices[sensor] = idx

    # If expected_samples was specified, use it; otherwise use max_index found
    for sensor in [1, 2]:
        limit = expected_samples if expected_samples is not None else (max_indices[sensor] + 1)
        if limit <= 0:
            continue

        # Build set of lost indices for this sensor
        lost_indices: Set[int] = set()
        for loss in losses:
            if loss.get("sensor") == sensor:
                f_idx = loss.get("from_index", 0)
                t_idx = loss.get("to_index")
                if t_idx is None:
                    # Session restart loss to end of known sequence
                    t_idx = limit - 1
                for i in range(f_idx, t_idx + 1):
                    lost_indices.add(i)

        # Check for unrecorded missing samples
        missing_run_start = None
        for i in range(limit):
            is_present = (sensor, i) in samples
            is_lost = i in lost_indices

            if not is_present and not is_lost:
                if missing_run_start is None:
                    missing_run_start = i
            else:
                if missing_run_start is not None:
                    silent_losses.append({
                        "sensor": sensor,
                        "from_index": missing_run_start,
                        "to_index": i - 1,
                        "count": i - missing_run_start
                    })
                    missing_run_start = None

        if missing_run_start is not None:
            silent_losses.append({
                "sensor": sensor,
                "from_index": missing_run_start,
                "to_index": limit - 1,
                "count": limit - missing_run_start
            })

    total_samples = len(samples)
    total_losses = len(losses)
    num_duplicates = len(duplicates)
    num_mismatches = len(value_mismatches)
    num_silent_losses = len(silent_losses)

    passed = (
        num_duplicates == 0
        and num_mismatches == 0
        and num_silent_losses == 0
        and total_samples > 0
    )

    stats = {
        "passed": passed,
        "total_samples": total_samples,
        "sensor_1_samples": sensor_counts[1],
        "sensor_2_samples": sensor_counts[2],
        "loss_records": total_losses,
        "duplicates": num_duplicates,
        "value_mismatches": num_mismatches,
        "silent_losses": num_silent_losses,
        "silent_loss_details": silent_losses[:10],
        "mismatch_details": value_mismatches[:5]
    }

    return passed, stats


def main():
    parser = argparse.ArgumentParser(description="Check export file against mock ground truth")
    parser.add_argument("export_file", help="Path to exported NDJSON file")
    parser.add_argument("--mode", choices=["signal", "ramp"], default="signal", help="Mode used: signal or ramp")
    parser.add_argument("--seed", type=int, default=7, help="Random seed used")
    parser.add_argument("--samples", type=int, default=None, help="Expected number of samples")

    args = parser.parse_args()
    passed, stats = check_export(args.export_file, mode=args.mode, seed=args.seed, expected_samples=args.samples)

    print(json.dumps(stats, indent=2))
    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()
